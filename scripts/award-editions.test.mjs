import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import test from 'node:test';
import assert from 'node:assert/strict';
const load=y=>JSON.parse(readFileSync(`data/festivals/years/${y}.json`)).editions;
for(const app of ['lab','lab-lite'])test(`${app}: ceremonies, special awards and category tabs remain independently accessible`,()=>{
 const html=readFileSync(`${app}/index.html`,'utf8');
 for(const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g))if(!/src=|application\/json/.test(m[1]))new vm.Script(m[2]);
 const lite=app==='lab-lite',pre=lite?'oscar':'award',cap=lite?'Oscar':'Award';
 const nodes=new Map(),calls=[];
 const $=id=>{
  if(id==='awardEditionSelect'&&!nodes.get('festSections')?.innerHTML.includes('id="awardEditionSelect"'))return null;
  if(!nodes.has(id))nodes.set(id,{innerHTML:'',textContent:'',querySelectorAll(){return []}});
  return nodes.get(id);
 };
 const context=vm.createContext({FESTIVAL_DB:{editions:[...load(1930),...load(1949)]},$,esc:s=>String(s),festivalEditionData:()=>({present:[],missing:[]}),renderFestivalEditionFor:(...a)=>calls.push(a)});
 vm.runInContext(readFileSync('app/festival-config.js','utf8'),context);
 const begin=html.indexOf(lite?'const BAFTA_CATEGORY_ORDER=':'const AWARD_CATEGORY_ORDER=');
 const end=html.indexOf(`function render${cap}Category(`,begin);
 vm.runInContext(html.slice(begin,end),context);
 context[`render${cap}Category`]=(...a)=>calls.push(a);
 const run=code=>vm.runInContext(code,context);
 run("renderSelectedAwardEdition(1930,'Oscar')");
 const first=run(`${pre}EditionRaw(1930,'Oscar').section`);
 assert.match(first,/2\.ª/);assert.match($('festSections').innerHTML,/3\.ª/);
 const select=$('awardEditionSelect');
 select.value=load(1930).find(e=>/3\.ª/.test(e.section)).section;select.onchange();
 assert.match(run(`${pre}EditionRaw(1930,'Oscar').section`),/3\.ª/);
 assert.match($('festDisplayTitle').textContent,/3\.ª/);
 assert.match($('festSections').innerHTML,new RegExp(`${pre}CategoryBtn`));
 assert.ok(calls.length>=2);
 const special=load(1949).find(e=>e.festival==='Oscar'&&/especial|honor/i.test(e.section));
 assert.ok(special,'real special awards section exists');
 run("selectedAwardSection=null;renderSelectedAwardEdition(1949,'Oscar')");
 const awardSelect=$('awardEditionSelect');awardSelect.value=special.section;awardSelect.onchange();
 assert.equal(run(`${pre}EditionRaw(1949,'Oscar').section`),special.section);
 assert.match($('festDisplayTitle').textContent,/especial|honor/i);
 const single=load(1949).filter(e=>e.festival==='BAFTA');
 context.FESTIVAL_DB.editions=single;
 run("selectedAwardSection=null;renderSelectedAwardEdition(1949,'BAFTA')");
 assert.equal($('awardEditionSelect'),null);
 assert.equal($('festDisplayTitle').textContent,'BAFTA 1949');
 context.FESTIVAL_DB.editions=load(2025).filter(e=>e.festival==='César');
 run("selectedAwardSection=null;renderSelectedAwardEdition(2025,'César')");
 assert.equal(run(`${pre}Categories(2025,'César').length`),24);
 assert.equal(run(`${pre}Categories(2025,'César')[0]`),'Película');
 assert.match($('festSections').innerHTML,new RegExp(`${pre}CategoryBtn`));
});
